/** Every prop: round 1's, the market stall's variants after its first (round 4), and the layout v2 props (./props2). */
const ALL_PROPS: Record<string, readonly PropDef[]> = { ...PROPS, stall: [...(PROPS.stall ?? []), ...marketStalls()], ...round4Props() };

export const PROP_KINDS = Object.keys(ALL_PROPS);

export interface BuiltProp {
  /** Outlined albedo (palette indices). */
  albedo: Indexed;
  /** Lit parts only, same size (palette indices), or null. */
  emissive: Indexed | null;
  /** The cell's top-left in the frame (the provider's anchor). */
  ax: number;
  ay: number;
  shadow: { footprint: [number, number][]; height: number } | null;
}

/** A banded light pool (stepped bands, as pixel-art pools are): band index per pixel, 0 outside. */
export interface Pool {
  w: number;
  h: number;
  bands: Uint8Array;
  /** Per band: colour and alpha (the renderer adds it with 'lighter'). */
  colours: readonly (readonly [number, number, number, number])[];
  /**
   * Round 2: the same light as a shape a renderer can fit to the town (clip it
   * to the ground, splash it up a wall): band edges as squared normalised
   * distance, brightest band first (band k is `colours[4 - k]`), and how high
   * up a wall the light reaches (px).
   */
  steps: readonly number[];
  rz: number;
}

/** Light from a lit shop window or door onto the pavement in front (round 2): depth (px) and stepped bands, brightest first. */
export interface Spill {
  depth: number;
  steps: readonly number[];
  colours: readonly (readonly [number, number, number, number])[];
}

/** Build every prop variant (ahead of time). */
export function buildProps(p: Palette, lightness: readonly number[]): Record<string, BuiltProp[]> {
  const legend = legendFor(p, { ...PROP_LEGEND_RAMPS, ...PROP2_LEGEND_RAMPS });
  const litLegend: Record<string, number> = { ...legend, g: legendFor(p, { l: ["lamp", 1] }).l as number, y: legendFor(p, { l: ["lamp", 2] }).l as number, G: legendFor(p, { l: ["lamp", 0] }).l as number };
  const out: Record<string, BuiltProp[]> = {};
  for (const [kind, defs] of Object.entries(ALL_PROPS)) {
    out[kind] = defs.map((d) => {
      const g = grid(d.grid, legend);
      // One pixel of room all round for the outline.
      const padded = blank(g.w + 2, g.h + 2);
      blit(padded, g, 1, 1);
      const albedo = outline(padded, p.lineOf, lightness);
      let emissive: Indexed | null = null;
      if (d.lit) {
        const rows = d.grid
          .split("\n")
          .filter((r) => r.trim())
          .map((r) => [...r.trim()].map((ch) => (d.lit?.includes(ch) ? ch : ".")).join(""));
        emissive = blank(g.w + 2, g.h + 2);
        blit(emissive, grid(rows.join("\n"), litLegend), 1, 1);
      }
      const ax = d.left !== undefined ? d.left + 1 : Math.floor((albedo.w - 16) / 2);
      const ay = d.base + 1 - 15;
      const shadow = d.shadow
        ? {
            footprint: [
              [d.shadow.box[0], d.shadow.box[1]],
              [d.shadow.box[2], d.shadow.box[1]],
              [d.shadow.box[2], d.shadow.box[3]],
              [d.shadow.box[0], d.shadow.box[3]],
            ] as [number, number][],
            height: d.shadow.height,
          }
        : null;
      return { albedo, emissive, ax, ay, shadow };
    });
  }
  return out;
}

/** The street lamp's light pool: an ellipse in four stepped bands of warm light. */
export function lampPool(p: Palette): Pool {
  const w = 48;
  const h = 26;
  const bands = new Uint8Array(w * h);
  const cx = (w - 1) / 2;
  const cy = (h - 1) / 2;
  for (let y = 0; y < h; y++) {
    for (let x = 0; x < w; x++) {
      // Integer-friendly ellipse distance, squared (no square roots needed: the bands are thresholds).
      const d = ((x - cx) / (w / 2)) ** 2 + ((y - cy) / (h / 2)) ** 2;
      bands[y * w + x] = d < 0.12 ? 4 : d < 0.35 ? 3 : d < 0.65 ? 2 : d < 1 ? 1 : 0;
    }
  }
  const lamp = p.colors[legendFor(p, { l: ["lamp", 0] }).l as number] as string;
  const rgb = [parseInt(lamp.slice(1, 3), 16), parseInt(lamp.slice(3, 5), 16), parseInt(lamp.slice(5, 7), 16)] as const;
  const colours = [
    [0, 0, 0, 0],
    [rgb[0], rgb[1], rgb[2], 0.1],
    [rgb[0], rgb[1], rgb[2], 0.17],
    [rgb[0], rgb[1], rgb[2], 0.25],
    [rgb[0], rgb[1], rgb[2], 0.33],
  ] as const;
  return { w, h, bands, colours, steps: [0.12, 0.35, 0.65], rz: 30 };
}

/** The light a lit window casts on the pavement: short, warm, two steps and a dithered edge. */
export function windowSpill(p: Palette): Spill {
  const lamp = p.colors[legendFor(p, { l: ["lamp", 1] }).l as number] as string;
  const rgb = [parseInt(lamp.slice(1, 3), 16), parseInt(lamp.slice(3, 5), 16), parseInt(lamp.slice(5, 7), 16)] as const;
  return {
    depth: 10,
    steps: [0.3, 0.65],
    colours: [
      [rgb[0], rgb[1], rgb[2], 0.28],
      [rgb[0], rgb[1], rgb[2], 0.18],
      [rgb[0], rgb[1], rgb[2], 0.09],
    ],
  };
}
