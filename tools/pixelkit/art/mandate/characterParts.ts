// Character parts for the P0 spike, drawn by hand as text grids (decision D5).
// Every part is drawn in slot colours, not real ones: the compositor
// recolours them from the palette per person (skin, hair, cloth ramps).
//
// Frame: 16×24, the figure in columns 0..14 centred on column 7, the soles on
// row 22 (the outline takes rows 0 and 23). Head grids are 15×14 with the
// face on rows 4..10 (rows 0..3 are room for volume, 11..13 for hair over the
// shoulders); torsos are 6 rows; legs are drawn at the middle length (5 rows
// standing, 6 on the passing frames, which lifts the body 1 px) and the
// compositor removes or repeats their stretch row (row 2) for short and tall
// figures. Side views face right; the left view is the mirror.
//
// Legend (uppercase is the shade step, a symbol the light step):
//   s S ^  skin          h H ~  hair          t T *  top (and sleeves)
//   r R    forearm: sleeve for long sleeves, skin for short
//   u U    upper leg: bottoms;  l L  lower leg: bottoms, or skin under shorts and skirts
//   p P    bottoms (skirt)      f F  shoes     a A +  accent (apron, tie)
//   o      eyes and dark detail w     white (collar, eye glint)

