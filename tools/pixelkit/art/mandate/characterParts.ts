// Character parts, drawn by hand as text grids (decision D5). Round 3: a
// flat, graphic style (PIXEL_ART_TOOL.md, "Round 3 results"). Every part is
// drawn in slot colours, not real ones: the compositor recolours them from
// the palette per person (skin, hair, cloth, hat and bag ramps).
//
// Frame: 16×24, the figure in columns 0..14 centred on column 7, the soles on
// row 22 (the outline takes rows 0 and 23). Head grids are 15×14 with the
// face on rows 4..10 (rows 0..3 are room for volume, 11..13 for hair over the
// shoulders); torsos are 6 rows; legs are drawn at the middle length (5 rows
// standing, 6 on the passing frames, which lifts the body 1 px: the walk's
// bob) and the compositor removes or repeats their stretch row (row 2) for
// short and tall figures. Side views face right; the left view is the mirror.
//
// Blocks hold the three views side by side, in the order DOWN  UP  SIDE.
//
// The flat rules (round 3):
//   - one flat colour per material, and at most one darker tone, used only as
//     a hard shape: a fringe's cut, a parting, curls, the hem, a pocket, the
//     far limb in the side view; never a gradient, a rim or a highlight;
//   - shapes before shading: people differ by the silhouette of their hair or
//     hat, their build, the cut of their clothes and what they carry;
//   - the face: 1×2 eyes (the smallest mark that reads as an eye at 1×), no
//     mouth; the side view has one eye and a 1 px nose; the back has nothing.
//
// Legend (uppercase is the one shade step):
//   s S    skin                 h H    hair
//   t T    top (and sleeves)    r R    forearm: sleeve for long sleeves, skin for short
//   u U    upper leg: bottoms;  l L    lower leg: bottoms, or skin under shorts and skirts
//   p P    bottoms (skirt, overalls)
//   f F    shoes                a A    accent (apron, tie, hi-vis, lanyard)
//   c C    hat (cap, headscarf) k K    bag
//   o      eyes, glasses        w      white (collar, lens, reflective band)
//   e      the top of an eye (dark; a light catch on the darkest skins)
// Round 1's light steps (^ ~ * +) are still read, as the base colour.

